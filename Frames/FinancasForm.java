    private interface Acao { void run(); }
    private interface Excluidor { void excluir(int id); }

    /** Executa a ação; mostra o erro ao usuário e devolve false se falhar. */
    private boolean executar(Acao acao) {
        try {
            acao.run();
            return true;
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Verifique os dados", JOptionPane.WARNING_MESSAGE);
        } catch (RuntimeException ex) {
            String msg = ex.getMessage() != null ? ex.getMessage()
                    : "Falha ao acessar o banco. Verifique se o MySQL está ligado.";
            JOptionPane.showMessageDialog(this, msg, "Erro", JOptionPane.ERROR_MESSAGE);
        }
        return false;
    }

    private void ligarSelecao(JTable tabela, final Acao acao) {
        tabela.getSelectionModel().addListSelectionListener(new ListSelectionListener() {
            public void valueChanged(ListSelectionEvent e) {
                if (!e.getValueIsAdjusting() && !carregando) {
                    acao.run();
                }
            }
        });
    }

    /** ID (coluna 0) da linha selecionada, ou -1 se não houver seleção. */
    private int idSelecionado(JTable tabela) {
        int linha = tabela.getSelectedRow();
        return linha < 0 ? -1 : ((Integer) tabela.getValueAt(linha, 0)).intValue();
    }

    private void reselecionar(JTable tabela, int id) {
        if (id == 0) {
            return;
        }
        for (int r = 0; r < tabela.getRowCount(); r++) {
            if (((Integer) tabela.getValueAt(r, 0)).intValue() == id) {
                tabela.setRowSelectionInterval(r, r);
                return;
            }
        }
    }

    private void excluirSelecionado(JTable tabela, final Excluidor exc, final Acao depois) {
        final int id = idSelecionado(tabela);
        if (id < 0) {
            JOptionPane.showMessageDialog(this, "Selecione uma linha na tabela.");
            return;
        }
        if (JOptionPane.showConfirmDialog(this, "Excluir o registro " + id + "?", "Confirmar",
                JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION) {
            if (executar(new Acao() {
                public void run() { exc.excluir(id); }
            })) {
                depois.run();
                carregarTudo();
            }
        }
    }

    private static String vazio(String s) {
        return s == null ? "" : s;
    }

    private static int idDe(Object o) {
        if (o instanceof Usuario) return ((Usuario) o).getId();
        if (o instanceof FonteRenda) return ((FonteRenda) o).getId();
        if (o instanceof Destinatario) return ((Destinatario) o).getId();
        return -1; // "(nenhum)"
    }

    /** Seleciona no combo o item com esse ID; com null volta para "(nenhum)". */
    private void selecionarCombo(JComboBox<Object> cmb, Integer id) {
        if (id == null) {
            if (cmb.getItemCount() > 0 && cmb.getItemAt(0) instanceof String) {
                cmb.setSelectedIndex(0);
            }
            return;
        }
        for (int i = 0; i < cmb.getItemCount(); i++) {
            if (idDe(cmb.getItemAt(i)) == id.intValue()) {
                cmb.setSelectedIndex(i);
                return;
            }
        }
    }

    /** Recarrega o combo preservando a seleção (comparando pelo ID, não pelo objeto). */
    private void recarregarCombo(JComboBox<Object> cmb, List<?> itens, boolean comOpcaoNenhum) {
        int anterior = idDe(cmb.getSelectedItem());
        cmb.removeAllItems();
        if (comOpcaoNenhum) {
            cmb.addItem(NENHUM);
        }
        if (itens != null){
            
            List<Object> listaOrdenada = new ArrayList<>(itens);
            listaOrdenada.sort(Comparator.comparing(
            item -> item == null ? "" : item.toString(), String.CASE_INSENSITIVE_ORDER));
            for (Object o : listaOrdenada) {
                cmb.addItem(o);
            }
        }
        selecionarCombo(cmb, anterior >= 0 ? Integer.valueOf(anterior) : null);
    }

