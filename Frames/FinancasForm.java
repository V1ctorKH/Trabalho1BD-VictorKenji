    /** Valida a tela e faz INSERT (idTrans == 0) ou UPDATE (idTrans != 0). */
    private void salvarTransacao() {
        if (!(cmbUsuario.getSelectedItem() instanceof Usuario)) {
            throw new IllegalArgumentException("Cadastre e selecione um usuário.");
        }
        if (!rdbCredito.isSelected() && !rdbDebito.isSelected()) {
            throw new IllegalArgumentException("Selecione Crédito ou Débito.");
        }
        double valor;
        try {
            valor = Double.parseDouble(txtValor.getText().trim().replace(',', '.'));
        } catch (NumberFormatException ex) {
            throw new IllegalArgumentException("Valor inválido.");
        }
        if (valor <= 0) {
            throw new IllegalArgumentException("O valor deve ser maior que zero.");
        }

        Transacao t = new Transacao();
        t.setId(idTrans);
        t.setIdUsuario(((Usuario) cmbUsuario.getSelectedItem()).getId());
        t.setIdFonte(cmbFonte.getSelectedItem() instanceof FonteRenda
                ? Integer.valueOf(((FonteRenda) cmbFonte.getSelectedItem()).getId()) : null);
        // Destinatário só existe em transações de débito; em crédito vai sempre nulo
        t.setIdDestinatario(rdbDebito.isSelected() && cmbDest.getSelectedItem() instanceof Destinatario
                ? Integer.valueOf(((Destinatario) cmbDest.getSelectedItem()).getId()) : null);
        t.setValor(valor);
        t.setTipo(rdbCredito.isSelected() ? "Crédito" : "Débito");
        t.setData(lerData(txtData.getText(), "Data", true));
        t.setFatura(chkFatura.isSelected());
        t.setDiaFatura(chkFatura.isSelected() ? lerData(txtDiaFatura.getText(), "Dia da fatura", false) : null);
        t.setDescricao(txtDescricao.getText().trim());

        if (idTrans == 0) transDAO.inserir(t); else transDAO.editar(t);
    }

    private void novaTransacao() {
        idTrans = 0;
        txtValor.setText("");
        txtData.setText(LocalDate.now().toString());
        txtDescricao.setText("");
        txtDiaFatura.setText("");
        chkFatura.setSelected(false);
        txtDiaFatura.setEnabled(false);
        btGroupTipo.clearSelection();
        atualizarDestinatario();
        btnTransSalvar.setText("Salvar");
        tblTrans.clearSelection();
    }

    private void carregarTransacaoSelecionada() {
        final int id = idSelecionado(tblTrans);
        if (id < 0) return;
        executar(new Acao() {
            public void run() {
                Transacao t = transDAO.buscarPorId(id);
                if (t == null) return;
                idTrans = t.getId();
                selecionarCombo(cmbUsuario, Integer.valueOf(t.getIdUsuario()));
                selecionarCombo(cmbFonte, t.getIdFonte());
                txtValor.setText(String.format(Locale.US, "%.2f", t.getValor()));
                txtData.setText(t.getData() != null ? t.getData().toString() : "");
                if ("Crédito".equals(t.getTipo())) {
                    rdbCredito.setSelected(true);
                } else {
                    rdbDebito.setSelected(true);
                }
                atualizarDestinatario();
                selecionarCombo(cmbDest, t.getIdDestinatario());
                chkFatura.setSelected(t.isFatura());
                txtDiaFatura.setEnabled(t.isFatura());
                txtDiaFatura.setText(t.getDiaFatura() != null ? t.getDiaFatura().toString() : "");
                txtDescricao.setText(vazio(t.getDescricao()));
                btnTransSalvar.setText("Atualizar");
            }
        });
    }

    /** O destinatário só pode ser escolhido quando a transação é de débito. */
    private void atualizarDestinatario() {
        boolean debito = rdbDebito.isSelected();
        cmbDest.setEnabled(debito);
        if (!debito && cmbDest.getItemCount() > 0) {
            cmbDest.setSelectedIndex(0); // volta para "(nenhum)"
        }
    }

    private LocalDate lerData(String texto, String campo, boolean hojeSeVazio) {
        if (texto.trim().isEmpty()) {
            if (hojeSeVazio) {
                return LocalDate.now();
            }
            throw new IllegalArgumentException(campo + " é obrigatório.");
        }
        try {
            return LocalDate.parse(texto.trim());
        } catch (DateTimeParseException ex) {
            throw new IllegalArgumentException(campo + " inválida. Use aaaa-mm-dd.");
        }
    }

