    private void carregarTudo() {
        if (mdlTrans == null) {
            return; // ainda dentro do construtor
        }
        executar(new Acao() {
            public void run() {
                carregando = true;
                try {
                    mdlUsr.setRowCount(0);
                    List<Usuario> usuarios = usuarioDAO.listar();
                    for (Usuario u : usuarios) {
                        mdlUsr.addRow(new Object[]{u.getId(), u.getNome(), u.getEmail()});
                    }
                    mdlFonte.setRowCount(0);
                    List<FonteRenda> fontes = fonteDAO.listar();
                    for (FonteRenda f : fontes) {
                        mdlFonte.addRow(new Object[]{f.getId(), f.getNome(), f.getDescricao()});
                    }
                    mdlDest.setRowCount(0);
                    List<Destinatario> dests = destDAO.listar();
                    for (Destinatario d : dests) {
                        mdlDest.addRow(new Object[]{d.getId(), d.getNome(), d.getDocumento()});
                    }
                    mdlTrans.setRowCount(0);
                    for (Object[] linha : transDAO.listarLinhas()) {
                        mdlTrans.addRow(linha);
                    }
                    recarregarCombo(cmbUsuario, usuarios, false);
                    recarregarCombo(cmbFonte, fontes, true);
                    recarregarCombo(cmbDest, dests, true);
                    recarregarCombo(cmbRelUsuario, usuarios, false);

                    // mantém marcada a linha que está em edição
                    reselecionar(tblUsr, idUsr);
                    reselecionar(tblFonte, idFonte);
                    reselecionar(tblDest, idDest);
                    reselecionar(tblTrans, idTrans);
                } finally {
                    carregando = false;
                }
            }
        });
    }

